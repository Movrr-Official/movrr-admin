const fs = require("node:fs"),
  path = require("node:path"),
  Module = require("node:module"),
  ts = require("typescript");
const root = path.resolve(__dirname, ".."),
  resolve = Module._resolveFilename;
Module._resolveFilename = function (r, p, ...rest) {
  return resolve.call(
    this,
    r.startsWith("@/") ? path.join(root, r.slice(2)) : r,
    p,
    ...rest,
  );
};
require.extensions[".ts"] = (m, f) =>
  m._compile(
    ts.transpileModule(fs.readFileSync(f, "utf8"), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    }).outputText,
    f,
  );
const t = require(
  path.join(root, "features/organisations/domain/employeeRoleTemplates.ts"),
);
const roles = [...new Set([...t.EMPLOYEE_ROLES, ...t.DASHBOARD_EMPLOYEE_ROLES])];
const grants = Object.fromEntries(
  roles.map((role) => [role, t.capabilitiesForEmployeeRole(role)]),
);
const sql = `-- Generated by scripts/generate-alignment-capabilities.cjs from canonical employee templates.\nCREATE OR REPLACE FUNCTION public.ops_employee_capabilities(p_role text) RETURNS jsonb\nLANGUAGE sql IMMUTABLE SET search_path='' AS $cap$ SELECT coalesce('${JSON.stringify(grants).replace(/'/g, "''")}'::jsonb->p_role,'[]'::jsonb) $cap$;\nREVOKE ALL ON FUNCTION public.ops_employee_capabilities(text) FROM PUBLIC,anon,authenticated,service_role;\n`;
const out = path.join(__dirname, "056_alignment_capabilities.sql");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(out, "utf8") !== sql)
    throw new Error("Regenerate alignment capability projection");
  console.log("Alignment SQL capabilities match canonical templates");
} else fs.writeFileSync(out, sql);
